"""Write and read tiers.yaml (LiteLLM Router model_list + router_settings)."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from tokenrouter.catalog.models import CatalogRow
from tokenrouter.catalog.tiering import top_members
from tokenrouter.config import Settings


def build_tiers_doc(rows: list[CatalogRow], settings: Settings, refreshed_at: str, refresh_id: int | None) -> dict:
    model_list: list[dict[str, Any]] = []
    tiers = settings.tier_names
    for tier in tiers:
        members = top_members(rows, tier, settings.top_n)
        for r in members:
            model_list.append(_deployment(tier, r.rank_in_tier, r.litellm_name, {}, {
                "model_id": r.model_id,
                "blended_price": r.blended_price,
                "usd_per_input_token": r.input_usd_per_m / 1e6,
                "usd_per_output_token": r.output_usd_per_m / 1e6,
                "intelligence_idx": r.intelligence_idx,
                "context_window": r.context_window,
                "supports_tools": r.supports_tools,
                "supports_json": r.supports_json,
            }))
        next_rank = len(members) + 1
        for i, extra in enumerate(settings.extra_members.get(tier, [])):
            model_list.append(_deployment(tier, next_rank + i, extra["litellm_name"], extra.get("litellm_params") or {}, {
                "model_id": extra["litellm_name"],
                "blended_price": 0.0,
                "usd_per_input_token": 0.0,
                "usd_per_output_token": 0.0,
                "intelligence_idx": extra.get("intelligence_idx"),
                "context_window": extra.get("context_window", 0),
                "supports_tools": extra.get("supports_tools", False),
                "supports_json": extra.get("supports_json", False),
                "extra_member": True,
            }))
    fallbacks = [{tiers[i]: [tiers[i + 1]]} for i in range(len(tiers) - 1)]
    return {
        "generated_at": refreshed_at,
        "refresh_id": refresh_id,
        "model_list": model_list,
        "router_settings": {"fallbacks": fallbacks},
    }


def _deployment(tier: str, rank: int, name: str, params: dict, info: dict) -> dict:
    return {
        "model_name": tier,
        "litellm_params": {"model": name, "order": rank, **params},
        "model_info": {"id": f"{tier}-{rank}", "router_tier": tier, "rank": rank, **info},
    }


def write_tiers_file(doc: dict, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by `tokenrouter refresh`. Do not hand-edit; change config/tokenrouter.yaml instead.\n"
    path.write_text(header + yaml.safe_dump(doc, sort_keys=False))


@dataclass(frozen=True)
class Deployment:
    tier: str
    rank: int
    litellm_name: str
    context_window: int
    supports_tools: bool
    blended_price: float
    input_cost_per_token: float
    output_cost_per_token: float


@dataclass
class TierTable:
    doc: dict[str, Any]

    @classmethod
    def load(cls, path: Path) -> "TierTable":
        if not path.exists():
            raise FileNotFoundError(f"{path} not found - run `tokenrouter refresh` first")
        return cls(yaml.safe_load(path.read_text()) or {})

    @property
    def model_list(self) -> list[dict[str, Any]]:
        return self.doc.get("model_list") or []

    @property
    def fallbacks(self) -> list[dict[str, list[str]]]:
        return (self.doc.get("router_settings") or {}).get("fallbacks") or []

    def deployments(self, tier: str) -> list[Deployment]:
        deps = [_to_deployment(d) for d in self.model_list if d["model_name"] == tier]
        return sorted(deps, key=lambda x: x.rank)

    def primary(self, tier: str) -> Deployment | None:
        deps = self.deployments(tier)
        return deps[0] if deps else None

    def find(self, litellm_name: str) -> Deployment | None:
        for d in self.model_list:
            if d["litellm_params"]["model"] == litellm_name:
                return _to_deployment(d)
        return None


def _to_deployment(d: dict) -> Deployment:
    info = d.get("model_info") or {}
    return Deployment(
        tier=d["model_name"],
        rank=int(info.get("rank", d["litellm_params"].get("order", 99))),
        litellm_name=d["litellm_params"]["model"],
        context_window=int(info.get("context_window") or 0),
        supports_tools=bool(info.get("supports_tools")),
        blended_price=float(info.get("blended_price") or 0),
        input_cost_per_token=float(info.get("usd_per_input_token") or 0),
        output_cost_per_token=float(info.get("usd_per_output_token") or 0),
    )
